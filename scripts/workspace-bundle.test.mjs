import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, cpSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { exportBundle, bindBundle, portableRows, prepareBundleConfig } from './workspace-bundle.mjs';

test('exports exact commits and relocates selected source without requiring the original checkout', () => {
  const root = mkdtempSync(join(tmpdir(), 'workspace-bundle-'));
  try {
    const repo = join(root, 'repo');
    mkdirSync(repo);
    const git = args => execFileSync('git', ['-C', repo, ...args], { encoding: 'utf8', windowsHide: true }).trim();
    git(['init', '-q']);
    git(['config', 'core.autocrlf', 'false']);
    git(['config', 'user.name', 'Bundle Test']);
    git(['config', 'user.email', 'bundle@example.test']);
    git(['config', 'filter.lfs.smudge', 'exit 91']);
    git(['config', 'filter.lfs.required', 'true']);
    writeFileSync(join(repo, '.gitattributes'), '*.asset filter=lfs\n');
    const pointer = 'version https://git-lfs.github.com/spec/v1\noid sha256:' + 'a'.repeat(64) + '\nsize 10\n';
    writeFileSync(join(repo, 'model.asset'), pointer);
    writeFileSync(join(repo, 'source.txt'), 'first version');
    writeFileSync(join(repo, 'LICENSE'), 'fixture license');
    git(['add', '.']); git(['commit', '-qm', 'first']);
    const first = git(['rev-parse', 'HEAD']);
    writeFileSync(join(repo, 'source.txt'), 'second version');
    git(['add', 'source.txt']);
    git(['update-index', '--add', '--cacheinfo', `160000,${first},third_party/fixture`]);
    const blob = git(['hash-object', '-w', 'source.txt']);
    git(['-c', 'core.protectNTFS=false', 'update-index', '--add', '--cacheinfo', `100644,${blob},history/12:34.txt`]);
    git(['-c', 'core.protectNTFS=false', 'update-index', '--add', '--cacheinfo', `100644,${blob},history/trailing /note.txt`]);
    git(['commit', '-qm', 'second']);
    const second = git(['rev-parse', 'HEAD']);
    writeFileSync(join(repo, 'source.txt'), 'uncommitted, must not export');
    const row = { repoId: 'owner/project', repoUrl: 'https://github.com/owner/project', repositoryPath: repo, teamId: 'team', clusterId: 'cluster' };
    const rows = [{ ...row, caseId: 'c1', baseSha: first }, { ...row, caseId: 'c2', baseSha: second }];
    const original = join(root, 'bundle');
    exportBundle(rows, original);
    const moved = join(root, 'relocated', 'workspaces');
    cpSync(original, moved, { recursive: true });
    rmSync(repo, { recursive: true });
    assert.equal(JSON.stringify(portableRows(rows)).includes(repo), false);
    const [binding] = bindBundle(portableRows(rows), moved, ['c1']);
    assert.equal(binding.isGitRepository, false);
    assert.equal(readFileSync(join(binding.repositoryPath, 'source.txt'), 'utf8'), 'first version');
    assert.equal(readFileSync(join(binding.repositoryPath, 'LICENSE'), 'utf8'), 'fixture license');
    assert.equal(readFileSync(join(binding.repositoryPath, 'model.asset'), 'utf8'), pointer);
    assert.equal(binding.versionEvidence.sourceRevision, first);
    const [other] = bindBundle(portableRows(rows), moved, ['c2']);
    assert.equal(readFileSync(join(other.repositoryPath, 'source.txt'), 'utf8'), 'second version');
    assert.equal(readFileSync(join(other.repositoryPath, 'history', process.platform === 'win32' ? '12_34.txt' : '12:34.txt'), 'utf8'), 'second version');
    writeFileSync(join(root, 'manifest.json'), JSON.stringify(portableRows(rows)));
    writeFileSync(join(root, 'plan.json'), JSON.stringify({ selectedCaseIds: ['c2'] }));
    writeFileSync(join(root, 'evaluation.json'), JSON.stringify({ workspaceManifest: './manifest.json', plan: './plan.json', baselineRoot: './baseline' }));
    const prepared = prepareBundleConfig(join(root, 'evaluation.json'), moved, join(root, 'run'));
    const config = JSON.parse(readFileSync(prepared.config));
    const manifest = JSON.parse(readFileSync(config.workspaceManifest));
    assert.equal(prepared.preparedCases, 1);
    assert.equal(manifest.length, 2);
    assert.equal(manifest[0].resolutionStatus, 'blocked');
    assert.equal(manifest[0].repositoryPath, null);
    assert.equal(manifest[1].workspaceReady, true);
    assert.equal(config.baselineRoot, join(root, 'baseline'));
    const index = JSON.parse(readFileSync(join(moved, 'bundle.json')));
    assert.deepEqual(index.versions[1].submodules, [{ path: 'third_party/fixture', commit: first }]);
    assert.deepEqual(index.versions[1].windowsPathMappings, [{ original: 'history/12:34.txt', extracted: 'history/12_34.txt' }]);
    const packageFile = join(root, 'delivery.zip');
    execFileSync(process.execPath, [fileURLToPath(new URL('./package-workspace-bundle.mjs', import.meta.url)), moved, packageFile], { windowsHide: true });
    const python = [process.env.PYTHON, 'python3', 'python'].filter(Boolean).find(command => {
      try { execFileSync(command, ['-c', 'import zipfile'], { stdio: 'ignore', windowsHide: true }); return true; } catch { return false; }
    });
    if (!python) throw new Error('Python 3 is required to read the delivery zip');
    const zipPy = (code, extra) => execFileSync(python, ['-c', code, packageFile, ...extra], { encoding: 'utf8', windowsHide: true });
    const entries = zipPy('import sys,zipfile; print("\\n".join(zipfile.ZipFile(sys.argv[1]).namelist()))', []).trim().split(/\r?\n/);
    assert.ok(entries.every(entry => entry.startsWith('workspaces/')));
    assert.ok(entries.some(entry => entry.includes('/sources/')));
    assert.ok(entries.every(entry => !entry.includes('/archives/')));
    const delivery = join(root, 'teacher-machine');
    mkdirSync(delivery);
    zipPy('import sys,zipfile; zipfile.ZipFile(sys.argv[1]).extractall(sys.argv[2])', [delivery]);
    const directRoot = join(delivery, 'workspaces');
    const [direct] = bindBundle(portableRows(rows), directRoot, ['c2']);
    assert.equal(readFileSync(join(direct.repositoryPath, 'source.txt'), 'utf8'), 'second version');
    assert.equal(readFileSync(join(direct.repositoryPath, 'history/12_34.txt'), 'utf8'), 'second version');
    assert.equal(readFileSync(join(direct.repositoryPath, 'history/trailing_/note.txt'), 'utf8'), 'second version');
    writeFileSync(join(root, 'evaluation.json'), JSON.stringify({ workspaceManifest: './manifest.json', plan: './plan.json', outputRoot: './original-results' }));
    const automatic = prepareBundleConfig(join(root, 'evaluation.json'), directRoot, join(root, 'auto-run'), true);
    assert.equal(JSON.parse(readFileSync(automatic.config)).outputRoot, join(root, 'original-results'));
    writeFileSync(direct.versionEvidence.path, '{}');
    assert.throws(() => bindBundle(portableRows(rows), directRoot, ['c2']), /receipt/);
    writeFileSync(join(moved, index.versions[0].archive), 'corrupt');
    assert.throws(() => bindBundle(rows, moved, ['c1']), /Damaged/);
  } finally { rmSync(root, { recursive: true, force: true }); }
});
